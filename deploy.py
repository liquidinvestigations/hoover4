def preflight_compose_yaml(cfg, side):
    """Strict-parse the compose files this side will use, before anything is built.

    podman-compose accepts YAML that Docker Compose rejects -- a duplicate mapping key
    is the one that has actually happened here, from an edit that removed a service's
    name line and left its `driver:` line behind to attach to the service above. That
    file deploys fine on a podman host and fails on a Docker host with
    `mapping key "driver" already defined`, which is a bad way to find out.

    PyYAML's own `safe_load` is NOT strict enough on its own -- it accepts a duplicate
    key and lets the last one win, which is exactly the case that has to be caught here,
    so the loader below rejects duplicates explicitly.

    Skipped when PyYAML is absent: this check is optional and not a dependency worth adding
    to a script whose whole job is to run before anything is installed.
    """
    try:
        import yaml
    except ImportError:
        return

    class _StrictLoader(yaml.SafeLoader):
        pass

    def _reject_duplicates(loader, node, deep=False):
        seen = {}
        for key_node, value_node in node.value:
            key = loader.construct_object(key_node, deep=deep)
            if key in seen:
                raise yaml.YAMLError(
                    'duplicate mapping key "%s" on line %d (first seen on line %d)'
                    % (key, key_node.start_mark.line + 1, seen[key] + 1))
            seen[key] = key_node.start_mark.line
        return {loader.construct_object(k, deep=deep): loader.construct_object(v, deep=deep)
                for k, v in node.value}

    _StrictLoader.add_constructor(
        yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG, _reject_duplicates)

    def _construct_merge_tag(loader, node):
        # `!override` and `!reset` are compose's own merge tags (used here to clear a
        # list-valued key an earlier -f file set, such as a service's ports). PyYAML's
        # SafeLoader has no constructor for either, so without this they fail the
        # strict parse below on syntax the real compose provider accepts.
        if isinstance(node, yaml.SequenceNode):
            return loader.construct_sequence(node, deep=True)
        if isinstance(node, yaml.MappingNode):
            return _reject_duplicates(loader, node, deep=True)
        return loader.construct_scalar(node)

    _StrictLoader.add_constructor("!override", _construct_merge_tag)
    _StrictLoader.add_constructor("!reset", _construct_merge_tag)

    for path in compose_files(cfg, side):
        try:
            with open(path, "r", encoding="utf-8") as fh:
                yaml.load(fh, Loader=_StrictLoader)
        except yaml.YAMLError as exc:
            fail("%s is not valid compose YAML:\n    %s"
                 % (path, str(exc).replace("\n", "\n    ")))


def temporal_shard_count_in_store(rt):
    """The shard count the Temporal persistence store was initialised with, or None.

    The live server is asked first because it is authoritative and cheap. With the
    server down, Cassandra still knows: shard-info rows are `type = 0` in
    `temporal.executions` and their ids run 1..N. Returns None when neither is
    reachable, which is the ordinary state of a stack that has never been started.
    """
    describe = rt.run(["exec", "temporal", "temporal", "operator", "cluster",
                       "describe", "--address", "temporal:7233", "-o", "json"],
                      capture_output=True, text=True)
    if describe.returncode == 0:
        try:
            count = int(json.loads(describe.stdout).get("historyShardCount", 0))
        except (ValueError, TypeError, json.JSONDecodeError):
            count = 0
        if count > 0:
            return count
    cql = rt.run(["exec", "temporal-cassandra", "cqlsh", "-u", "cassandra",
                  "-p", "cassandra", "-e",
                  "SELECT shard_id FROM temporal.executions WHERE type=0 ALLOW FILTERING;"],
                 capture_output=True, text=True)
    if cql.returncode != 0:
        return None
    ids = [int(tok) for tok in cql.stdout.split() if tok.isdigit()]
    return max(ids) if ids else None


def preflight_temporal_shards(cfg, side, rt):
    """Refuse to start against a store initialised with a different shard count.

    `numHistoryShards` is immutable for the life of the persistence store: the server
    will not open a keyspace that was set up with another value. Left to itself it dies
    with a Cassandra error that names neither number, so catch it here and say what the
    two values are and how to reconcile them.
    """
    if side != "main":
        return
    want = cfg.get("main_services", "temporal_history_shards")
    try:
        want = int(want)
    except ValueError:
        fail("[main_services] temporal_history_shards is not a number: %r" % want)
    if want < 1:
        fail("[main_services] temporal_history_shards must be at least 1")
    have = temporal_shard_count_in_store(rt)
    if have is None or have == want:
        return
    fail("Temporal's store is initialised with %d history shards but hoover4.ini asks "
         "for %d. The count is fixed for the life of the store, so the server would "
         "refuse to start.\n"
         "    ./deploy --reset-temporal    drop Temporal's history and re-initialise "
         "at %d (leaves ClickHouse, Garage and Manticore alone)\n"
         "    set temporal_history_shards = %d in hoover4.ini to keep the store as it is"
         % (have, want, want, have))


