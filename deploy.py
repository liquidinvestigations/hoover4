class Runtime:
    """Container runtime detection. This repo runs on podman with the docker shim and
    podman-compose as the compose provider; plain docker is supported too."""

    def __init__(self):
        self.docker = shutil.which("docker")
        self.podman = shutil.which("podman")
        if not self.docker and not self.podman:
            fail("no container runtime found: looked for 'docker' and 'podman' on PATH")
        self.name = "podman" if self.podman else "docker"
        self.engine = self.podman or self.docker

    def compose_prefix(self):
        # Both docker (shim) and podman delegate `compose` to the installed provider
        # (podman-compose / docker-compose plugin).
        return [self.docker or self.podman, "compose"]

    def describe(self):
        return self.name

    def run(self, args, **kwargs):
        return subprocess.run([self.engine] + args, **kwargs)


