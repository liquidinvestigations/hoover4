_SIZE_UNITS = {"": 1, "K": 1024, "M": 1024 ** 2, "G": 1024 ** 3, "T": 1024 ** 4}


def size_bytes(cfg, key):
    """A `[main_services]` size such as `16000M` or `8G`, in bytes. Units are binary."""
    raw = cfg.get("main_services", key).strip()
    match = re.fullmatch(r"(\d+)\s*([KMGT]?)B?", raw, re.IGNORECASE)
    if not match:
        fail("[main_services] %s is not a size such as 8G or 16000M: %r" % (key, raw))
    return int(match.group(1)) * _SIZE_UNITS[match.group(2).upper()]


def whole_number(cfg, key, minimum=1, section="main_services"):
    raw = cfg.get(section, key).strip()
    try:
        value = int(raw)
    except ValueError:
        fail("[%s] %s is not a whole number: %r" % (section, key, raw))
    if value < minimum:
        fail("[%s] %s must be at least %d, got %d" % (section, key, minimum, value))
    return value


def operation_caps_value(cfg):
    """The `[operations]` caps as `kind=value` pairs joined by commas, in key order.

    Each cap is a whole number of at least 1. A key in `[operations]` that is not a cap
    of DEFAULTS prints a warning that names it, and the render goes on without it.
    """
    for key in cfg.extra.get("operations", []):
        print("warning: [operations] %s is not a known key, so it is ignored" % key)
    pairs = []
    for key in DEFAULTS["operations"]:
        value = whole_number(cfg, key, minimum=1, section="operations")
        pairs.append("%s=%d" % (key[:-len("_cap")], value))
    return ",".join(pairs)


def cpu_count_value(cfg, key):
    raw = cfg.get("main_services", key).strip()
    try:
        value = float(raw)
    except ValueError:
        fail("[main_services] %s is not a number of CPUs: %r" % (key, raw))
    if value <= 0:
        fail("[main_services] %s must be above 0, got %r" % (key, raw))
    return value


#: The CPU keys that become a container CPU limit.
CPU_LIMIT_KEYS = ("cassandra_cpus", "temporal_cpus", "tesseract_cpu_cpus")


def cpu_host_refusals(cfg):
    """A message for each CPU key above the CPU count of this host.

    Docker refuses a CPU limit above the CPU count of the host, and the container then
    does not start. deploy.py refuses these keys only on a command that starts
    containers. `--down` and the reset flags run with any value, and `--print-env`
    prints each message as a warning.
    """
    host_cpus = os.cpu_count()
    out = []
    for key in CPU_LIMIT_KEYS:
        raw = cfg.get("main_services", key).strip()
        if not raw:
            continue
        value = cpu_count_value(cfg, key)
        if host_cpus and value > host_cpus:
            out.append("[main_services] %s = %s is above the %d CPUs of this host. Set it "
                       "to %d or less." % (key, raw, host_cpus, host_cpus))
    return out


def volumes_path_problem(cfg):
    """Why `[storage] volumes_path` cannot be used, or None."""
    raw = cfg.get("storage", "volumes_path").strip()
    if not raw:
        return ("[storage] volumes_path is empty. Set it to the absolute host folder that "
                "holds the volume folders, for example /srv/hoover4-volumes.")
    if not os.path.isabs(raw):
        return ("[storage] volumes_path = %s is not an absolute path. Set it to an "
                "absolute host folder, for example /srv/hoover4-volumes." % raw)
    return None


def volumes_path(cfg):
    """The validated `[storage] volumes_path`."""
    problem = volumes_path_problem(cfg)
    if problem:
        fail(problem)
    return cfg.get("storage", "volumes_path").strip()


def start_refusals(cfg, side):
    """Every refusal of a command that starts containers, as messages."""
    out = []
    problem = volumes_path_problem(cfg)
    if problem:
        out.append(problem)
    if side == "main":
        out.extend(cpu_host_refusals(cfg))
    return out


def side_volumes(cfg, side):
    """The rows of VOLUMES that the selected side mounts."""
    sides = {side}
    if side == "main" and cfg.get_bool("main_services", "serena_enabled"):
        sides.add("serena")
    return [row for row in VOLUMES if row.side in sides]


def volume_folder(path, row):
    """`<volumes_path>/<volume name>`. The only form of path deploy.py writes to."""
    if row not in VOLUMES:
        fail("%r is not a row of VOLUMES" % (row,))
    return Path(path) / row.name


def create_volume_folders(cfg, side):
    """Create volumes_path, its parents, and one folder for each volume of the side."""
    root = volumes_path(cfg)
    for row in side_volumes(cfg, side):
        folder = volume_folder(root, row)
        try:
            folder.mkdir(parents=True, exist_ok=True)
        except OSError as exc:
            fail("cannot create %s for [storage] volumes_path: %s" % (folder, exc))


def resolve_image(template, env):
    """The image string with each `${VAR}` and `${VAR:-default}` read from env."""
    def one(match):
        name, default = match.group(1), match.group(3)
        value = env.get(name, "")
        if value:
            return value
        if default is not None:
            return default
        fail("image %s needs %s, which the rendered .env does not set" % (template, name))
    return re.sub(r"\$\{([A-Z0-9_]+)(:-([^}]*))?\}", one, template)


def chown_command(folder, row, image):
    """The one-shot container that gives a volume folder its owner. Not recursive,
    because every folder starts empty."""
    return ["run", "--rm", "--user", "0", "--entrypoint", "chown",
            "-v", "%s:/d" % folder, image, "%d:%d" % (row.uid, row.gid), "/d"]


def empty_command(folder, image):
    """The one-shot container that removes everything inside a volume folder. It runs
    in a container because the files belong to the uids of the services."""
    return ["run", "--rm", "--user", "0", "--entrypoint", "sh",
            "-v", "%s:/d" % folder, image, "-c", "find /d -mindepth 1 -delete"]


def set_volume_owners(cfg, side, rt, env):
    """Give each volume folder of the side the owner its service writes as."""
    root = volumes_path(cfg)
    for row in side_volumes(cfg, side):
        if row.uid == 0:
            continue
        folder = volume_folder(root, row)
        image = resolve_image(row.image, env)
        print("volumes: owner %d:%d for %s" % (row.uid, row.gid, folder))
        result = rt.run(chown_command(folder, row, image), capture_output=True, text=True)
        if result.returncode != 0:
            fail("could not set the owner of %s: %s"
                 % (folder, (result.stderr or "").strip()))


#: The script the one-time weight download runs inside the model server's image. It
#: reads the repository id from M and an optional token from the mounted token file.
DGEMMA_DOWNLOAD_SCRIPT = (
    "import os; from huggingface_hub import snapshot_download; "
    "t = open('/run/secrets/hf_token').read().strip() or None; "
    "snapshot_download(repo_id=os.environ['M'], local_dir='/models/dgemma', token=t)"
)


def dgemma_image(cfg):
    """The image tag of hoover4-vllm, as ai_services/compose/vllm.yaml writes it."""
    return "hoover4-vllm-dgemma:%s" % cfg.get("ai_services", "vllm_build_ref").strip()


def weights_complete(folder):
    """Whether folder holds config.json and every shard that the safetensors index names,
    each with a size above zero. A folder with no index needs config.json and one
    non-empty *.safetensors file."""
    folder = Path(folder)
    if not (folder / "config.json").is_file():
        return False
    index = folder / "model.safetensors.index.json"
    if not index.is_file():
        return any(p.stat().st_size > 0 for p in folder.glob("*.safetensors"))
    try:
        weight_map = json.loads(index.read_text()).get("weight_map") or {}
    except (OSError, ValueError):
        return False
    for shard in set(weight_map.values()):
        path = folder / shard
        if not path.is_file() or path.stat().st_size == 0:
            return False
    return bool(weight_map)


def dgemma_download_command(cfg, folder):
    """The one-shot container that downloads the weights into folder."""
    token = cfg.get("ai_services", "hf_token_file").strip() or "/dev/null"
    return ["run", "--rm", "--entrypoint", "python3",
            "-v", "%s:/models/dgemma" % folder,
            "-v", "%s:/run/secrets/hf_token:ro" % token,
            "-e", "HF_HUB_OFFLINE=0",
            "-e", "M=%s" % cfg.get("ai_services", "vllm_model").strip(),
            dgemma_image(cfg), "-c", DGEMMA_DOWNLOAD_SCRIPT]


def ensure_dgemma_weights(cfg, rt):
    """Download the model server's weights once into the dgemma_model folder.

    Runs on the ai side after the image exists and before `up`, only when
    llm_selfhosted is true. A complete folder is kept. The download resumes a partial
    folder, and deploy.py fails when the folder is still incomplete after it.
    """
    row = [r for r in VOLUMES if r.name == "dgemma_model"][0]
    folder = volume_folder(volumes_path(cfg), row)
    if weights_complete(folder):
        return
    model = cfg.get("ai_services", "vllm_model").strip()
    print("weights: downloading %s into %s. This runs for several minutes."
          % (model, folder))
    result = rt.run(dgemma_download_command(cfg, folder))
    if result.returncode != 0 or not weights_complete(folder):
        fail("the weights of %s are incomplete in %s" % (model, folder))


def ensure_dgemma_image(cfg, rt):
    """Build the model server's image when it does not exist yet. The weight download
    runs in this image, so it has to exist before `up` builds it."""
    found = rt.run(["image", "inspect", dgemma_image(cfg)],
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    if found.returncode == 0:
        return
    print("build: %s does not exist yet, so it is built first" % dgemma_image(cfg))
    run_or_fail(compose_command(cfg, "ai", rt, ["build", "hoover4-vllm"]))


def _folder_is_empty(folder):
    try:
        return not any(folder.iterdir())
    except PermissionError:
        return False


def empty_volume_folders(cfg, side, rt, env, classes, label):
    """Empty the volume folders of the side whose reset class is in classes.

    The folders themselves and volumes_path stay. A folder that does not exist or is
    already empty is skipped, so a reset pulls no image for it.
    """
    root = volumes_path(cfg)
    for row in side_volumes(cfg, side):
        folder = volume_folder(root, row)
        if row.reset_class not in classes:
            if row.reset_class == "cache":
                print("%s: preserving cache folder %s" % (label, folder))
            continue
        if not folder.is_dir() or _folder_is_empty(folder):
            continue
        image = resolve_image(row.image, env)
        result = rt.run(empty_command(folder, image), capture_output=True, text=True)
        if result.returncode != 0:
            fail("could not empty %s: %s" % (folder, (result.stderr or "").strip()))
        print("%s: emptied %s" % (label, folder))


#: Native memory the Cassandra JVM uses beyond its heap and its direct memory, which is
#: metaspace, thread stacks, the chunk cache bookkeeping and malloc arenas.
CASSANDRA_NATIVE_HEADROOM_BYTES = 3 * 1024 ** 3

#: The compose reservation of temporal-cassandra, lowered to the limit when the limit is
#: smaller.
CASSANDRA_RESERVATION_BYTES = 5000 * 1024 ** 2


def render_cassandra_env(cfg):
    """The temporal-cassandra variables, after the memory check.

    The container is killed when the heap, the direct memory and the native memory
    together pass the limit, so a limit below their sum is refused here.
    """
    m = "main_services"
    limit = size_bytes(cfg, "cassandra_mem_limit")
    heap = size_bytes(cfg, "cassandra_heap")
    direct = size_bytes(cfg, "cassandra_direct_memory")
    if limit < heap + direct + CASSANDRA_NATIVE_HEADROOM_BYTES:
        fail("[main_services] cassandra_mem_limit = %s is smaller than cassandra_heap = %s "
             "plus cassandra_direct_memory = %s plus 3G of native memory. Raise the "
             "limit, or lower the heap or the direct memory."
             % (cfg.get(m, "cassandra_mem_limit"), cfg.get(m, "cassandra_heap"),
                cfg.get(m, "cassandra_direct_memory")))
    cpus = cpu_count_value(cfg, "cassandra_cpus")
    heap_new = cfg.get(m, "cassandra_heap_new").strip()
    if not heap_new:
        heap_new = "%dM" % int(100 * cpus)
    env = {
        "CASSANDRA_MEM_LIMIT": cfg.get(m, "cassandra_mem_limit"),
        "CASSANDRA_MEM_RESERVATION": "%dM" % (
            min(limit, CASSANDRA_RESERVATION_BYTES) // 1024 ** 2),
        "CASSANDRA_CPUS": cfg.get(m, "cassandra_cpus"),
        "CASSANDRA_HEAP": cfg.get(m, "cassandra_heap"),
        "CASSANDRA_HEAP_NEW": heap_new,
        "CASSANDRA_JVM_EXTRA_OPTS": "-XX:MaxDirectMemorySize=%s"
                                    % cfg.get(m, "cassandra_direct_memory"),
        "CASSANDRA_CHUNK_CACHE_MB": str(whole_number(cfg, "cassandra_chunk_cache_mb", 0)),
    }
    if cfg.get(m, "cassandra_malloc_arenas").strip():
        env["CASSANDRA_MALLOC_ARENAS"] = str(whole_number(cfg, "cassandra_malloc_arenas"))
    return env


#: The tracked dynamic config and the file deploy.py renders beside it. The temporal
#: service reads the generated file, which holds every key of the tracked file.
TEMPORAL_DYNAMIC_CONFIG_DIR = MAIN_COMPOSE_DIR / "temporal-dynamicconfig"
TEMPORAL_DYNAMIC_CONFIG_TRACKED = TEMPORAL_DYNAMIC_CONFIG_DIR / "docker.yaml"
TEMPORAL_DYNAMIC_CONFIG_GENERATED = TEMPORAL_DYNAMIC_CONFIG_DIR / "generated.yaml"

#: (ini key, dynamic config key) of each persistence rate limit.
TEMPORAL_PERSISTENCE_QPS_KEYS = (
    ("temporal_history_persistence_qps", "history.persistenceMaxQPS"),
    ("temporal_frontend_persistence_qps", "frontend.persistenceMaxQPS"),
    ("temporal_matching_persistence_qps", "matching.persistenceMaxQPS"),
)


def render_temporal_dynamic_config(cfg, tracked_text=None):
    """The text of generated.yaml: the tracked docker.yaml, then each rate limit set.

    Temporal reads one dynamic config file, so the generated file carries the tracked
    keys too. The tracked file must not set a key that the ini also sets, because a
    YAML mapping with a repeated key is refused.
    """
    if tracked_text is None:
        tracked_text = TEMPORAL_DYNAMIC_CONFIG_TRACKED.read_text(encoding="utf-8")
    lines = [ENV_HEADER.rstrip("\n"), tracked_text.rstrip("\n"), ""]
    for ini_key, dc_key in TEMPORAL_PERSISTENCE_QPS_KEYS:
        if not cfg.get("main_services", ini_key).strip():
            continue
        value = whole_number(cfg, ini_key)
        if re.search(r"^%s:" % re.escape(dc_key), tracked_text, re.MULTILINE):
            fail("[main_services] %s sets %s, which %s already sets"
                 % (ini_key, dc_key, TEMPORAL_DYNAMIC_CONFIG_TRACKED.name))
        lines += ["# From [main_services] %s." % ini_key,
                  "%s:" % dc_key, "  - value: %d" % value, ""]
    return "\n".join(lines).rstrip("\n") + "\n"


#: The memory limit of hoover4-tesseract-cpu when tesseract_cpu_mem_limit is empty: a base
#: for the server, and more for each concurrent Tesseract run.
TESSERACT_BASE_MEM_MB = 4096
TESSERACT_MEM_PER_THREAD_MB = 1024


def render_tesseract_env(cfg):
    """The hoover4-tesseract-cpu variables.

    An empty tesseract_cpu_mem_limit gives 4096M plus 1024M for each unit of
    tesseract_cpu_concurrency. Every other empty key renders no variable.
    """
    m = "main_services"
    concurrency = whole_number(cfg, "tesseract_cpu_concurrency")
    env = {
        "TESSERACT_CPU_CONCURRENCY": str(concurrency),
        "TESSERACT_CPU_QUEUE_DEPTH": str(4 * concurrency),
    }
    if cfg.get(m, "tesseract_threads_per_page").strip():
        env["TESSERACT_THREADS_PER_PAGE"] = str(whole_number(cfg, "tesseract_threads_per_page"))
    if cfg.get(m, "tesseract_cpu_cpus").strip():
        env["TESSERACT_CPU_CPUS"] = cfg.get(m, "tesseract_cpu_cpus").strip()
        cpu_count_value(cfg, "tesseract_cpu_cpus")
    if cfg.get(m, "tesseract_cpu_mem_limit").strip():
        size_bytes(cfg, "tesseract_cpu_mem_limit")
        env["TESSERACT_CPU_MEM_LIMIT"] = cfg.get(m, "tesseract_cpu_mem_limit").strip()
    else:
        env["TESSERACT_CPU_MEM_LIMIT"] = "%dM" % (
            TESSERACT_BASE_MEM_MB + TESSERACT_MEM_PER_THREAD_MB * concurrency)
    return env


def ocr_concurrency_warning(cfg):
    """A warning when the worker sends fewer OCR requests than Tesseract can serve."""
    ocr = cfg.get("main_services", "ocr_concurrency").strip()
    if not ocr or not cfg.get_bool("main_services", "tesseract_cpu_enabled"):
        return None
    tesseract = cfg.get("main_services", "tesseract_cpu_concurrency").strip()
    if ocr.isdigit() and tesseract.isdigit() and int(ocr) < int(tesseract):
        return ("warning: [main_services] ocr_concurrency = %s is lower than "
                "tesseract_cpu_concurrency = %s, so Tesseract slots stay idle"
                % (ocr, tesseract))
    return None


