def load_config(args):
    if INI_PATH.exists():
        return Config(INI_PATH)
    if args.print_env or args.print_command:
        print("note: hoover4.ini not found — rendering from hoover4.ini.example "
              "defaults", file=sys.stderr)
        if not INI_EXAMPLE_PATH.exists():
            fail("neither hoover4.ini nor hoover4.ini.example exists")
        return Config(INI_EXAMPLE_PATH)
    fail("hoover4.ini not found. Create it from the tracked template:\n"
         "    cp hoover4.ini.example hoover4.ini && $EDITOR hoover4.ini")


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Deploy hoover4 from hoover4.ini.")
    parser.add_argument("--ai-services", action="store_true",
                        help="deploy the ai_services side instead of main_services")
    parser.add_argument("--print-env", action="store_true",
                        help="render and show the .env files, start nothing")
    parser.add_argument("--print-command", action="store_true",
                        help="show the docker compose invocation, run nothing")
    parser.add_argument("--build", action="store_true", help="build images first")
    parser.add_argument("--down", action="store_true",
                        help="compose down for the selected side")
    parser.add_argument("--reset", action="store_true",
                        help="compose down and remove the project's data volumes "
                             "(model caches and Serena are preserved)")
    parser.add_argument("--reset-caches", action="store_true",
                        help="with --reset: also remove the model-cache volumes")
    parser.add_argument("--reset-temporal", action="store_true",
                        help="drop Temporal's history and visibility stores only, "
                             "keeping ClickHouse/Garage/Manticore; required to change "
                             "temporal_history_shards")
    args = parser.parse_args(argv)

    side = "ai" if args.ai_services else "main"
    cfg = load_config(args)
    rt = Runtime()

    if args.print_env:
        env = render_ai_env(cfg) if side == "ai" else render_main_env(cfg)
        path = AI_COMPOSE_DIR / ".env" if side == "ai" else MAIN_COMPOSE_DIR / ".env"
        print("# would write %s:" % path)
        print(ENV_HEADER, end="")
        for key in sorted(env):
            print("%s=%s" % (key, env[key]))
        return 0

    if args.print_command:
        action = ["down"] if args.down else ["up", "-d"] + (["--build", "--force-recreate"] if args.build else [])
        if side == "ai" and not cfg.get_bool("ai_services", "enabled"):
            # Show what WOULD run, but do not let the output imply the tier is
            # deployable: a real `--ai-services` run refuses in the preflights.
            print("note: [ai_services] enabled = false — a real --ai-services run "
                  "refuses; the command below is what it would render if enabled",
                  file=sys.stderr)
        cmd = compose_command(cfg, side, rt, action)
        print(" ".join(cmd))
        if side == "main" and not args.down and cfg.get_bool("main_services", "serena_enabled"):
            print(" ".join(serena_command(cfg, rt, action)))
        return 0

    starting = not (args.down or args.reset or args.reset_temporal)
    run_preflights(cfg, side, rt, starting)

    # Render the generated .env next to the compose files.
    if side == "ai":
        changed = write_env_file(AI_COMPOSE_DIR / ".env", render_ai_env(cfg))
        env_path = AI_COMPOSE_DIR / ".env"
    else:
        changed = write_env_file(MAIN_COMPOSE_DIR / ".env", render_main_env(cfg))
        env_path = MAIN_COMPOSE_DIR / ".env"
    print("rendered %s%s" % (env_path, " (changed)" if changed else " (unchanged)"))

    if args.down:
        compose_down(cfg, side, rt)
        return 0

    if args.reset:
        compose_reset(cfg, side, rt, args.reset_caches)
        return 0

    if args.reset_temporal:
        compose_reset_temporal(cfg, side, rt)
        return 0

    if side == "ai":
        ensure_network(rt, "ai_services")
    else:
        # The main stack's network is declared in the compose file without DNS
        # settings; create/repair it ourselves first so compose finds it already
        # configured. Without this, aardvark-dns forwards to the host's 127.*
        # resolver stub and external DNS is wedged stack-wide.
        ensure_network(rt, "hoover4")
    compose_up(cfg, side, rt, args.build)
    if side == "ai":
        verify_network_dns(rt, cfg, side)
        reprobe_embeddings(rt)
    else:
        # Serena is deployed as its own project, AFTER the main stack: the MCP server
        # the agent talks through must not share a project with anything `down` or
        # `--reset` can select.
        compose_up_serena(cfg, rt, args.build)
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except DeployError as exc:
        print("deploy: error: %s" % exc, file=sys.stderr)
        sys.exit(1)
