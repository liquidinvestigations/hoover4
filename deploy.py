def preflight_gpu(cfg, side):
    """GPU overlays requested -> nvidia-smi must work, and on podman a CDI spec must
    exist. Refuses before compose runs, so a missing CDI never surfaces as an
    unfriendly OCI mount error at container start."""
    if side != "ai":
        return
    requested = [rel for rel in selected_overlays(cfg, "ai") if rel in AI_GPU_OVERLAYS]
    if not requested:
        return
    smi = shutil.which("nvidia-smi")
    if not smi or subprocess.run([smi], stdout=subprocess.DEVNULL,
                                 stderr=subprocess.DEVNULL).returncode != 0:
        fail("nvidia-smi failed (no usable NVIDIA GPU), but GPU overlays were "
             "requested: %s" % ", ".join(requested))
    cdi_ok = os.path.exists(CDI_SPEC)
    if not cdi_ok and shutil.which("nvidia-ctk"):
        cdi_ok = subprocess.run(
            ["nvidia-ctk", "cdi", "list"], stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL).returncode == 0
    if not cdi_ok:
        fail("GPU overlays requested (%s) but no NVIDIA CDI spec found at %s.\n"
             "Generate it with:\n"
             "    sudo nvidia-ctk cdi generate --output=%s"
             % (", ".join(requested), CDI_SPEC, CDI_SPEC))


def preflight_cdi_prune(rt):
    """Fold of ai_services/start-docker.sh: drop CDI mounts whose host path does not
    exist — a partial driver upgrade leaves entries pointing at files that were never
    installed, and crun refuses to start the GPU containers over a missing bind
    source. Host-A (ai_services) preflight."""
    if not os.path.isfile(CDI_SPEC) or not os.access(CDI_SPEC, os.R_OK):
        print("preflight: no readable CDI spec at %s — skipping prune" % CDI_SPEC)
        return
    with open(CDI_SPEC, "r", encoding="utf-8") as fh:
        lines = fh.readlines()
    stale = []
    for line in lines:
        match = re.match(r"^\s*-?\s*hostPath:\s*(\S+)\s*$", line)
        if match and not os.path.exists(match.group(1)):
            stale.append(match.group(1))
    if not stale:
        print("preflight: CDI spec ok — every mount resolves")
        return
    for path in stale:
        print("preflight: CDI spec references missing file: %s" % path)
    # Remove the whole list item (hostPath + its containerPath/options lines).
    pruned = []
    skip_block = False
    for i, line in enumerate(lines):
        item = re.match(r"^(\s*)-\s*hostPath:\s*(\S+)\s*$", line)
        if item:
            skip_block = item.group(2) in stale
        elif skip_block and re.match(r"^\S", line):
            skip_block = False
        elif skip_block and re.match(r"^\s+-\s+hostPath:", line):
            skip_block = False
            pruned.append(line)
            continue
        if not skip_block:
            pruned.append(line)
    if shutil.which("sudo") and subprocess.run(
            ["sudo", "-n", "true"], stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL).returncode == 0:
        backup = "%s.bak-deploy" % CDI_SPEC
        subprocess.run(["sudo", "cp", "-a", CDI_SPEC, backup], check=True)
        import tempfile
        with tempfile.NamedTemporaryFile("w", delete=False) as tmp:
            tmp.writelines(pruned)
            tmp_path = tmp.name
        subprocess.run(["sudo", "cp", tmp_path, CDI_SPEC], check=True)
        subprocess.run(["sudo", "chmod", "644", CDI_SPEC], check=True)
        os.unlink(tmp_path)
        print("preflight: CDI spec patched (previous at %s)" % backup)
    else:
        print("preflight: WARNING: %s needs root to fix and sudo is not available; "
              "GPU services may fail with an OCI runtime error" % CDI_SPEC)


def preflight_secrets(cfg):
    repo = str(REPO_ROOT)
    for section, key, path in cfg.secret_files():
        if not os.path.exists(path):
            fail("[%s] %s: secret file is missing: %s" % (section, key, path))
        mode = stat.S_IMODE(os.stat(path).st_mode)
        if mode & (stat.S_IRWXG | stat.S_IRWXO):
            fail("[%s] %s: secret file %s is group/world accessible (mode %04o); "
                 "chmod 600 it" % (section, key, path, mode))
        real = os.path.realpath(path)
        if real == repo or real.startswith(repo + os.sep):
            fail("[%s] %s: secret file %s is inside the repository checkout — keys "
                 "inside the checkout leak into build contexts and commits"
                 % (section, key, path))


def local_ip_addresses():
    """Every IPv4 address configured on this machine, plus loopback."""
    addrs = {"127.0.0.1", "localhost", "0.0.0.0"}
    try:
        out = subprocess.run(["ip", "-4", "-o", "addr"], capture_output=True,
                             text=True).stdout
        addrs.update(re.findall(r"inet (\d+\.\d+\.\d+\.\d+)", out))
    except OSError:
        pass
    return addrs


def container_reachable_host(host):
    """Rewrite an ai_services host that is *this* machine into a name containers
    can actually route to.

    ai_services lives on its own private network and main_services reaches it
    over the published ports on `[ai_services] host`. That
    works when the GPU tier is a different box. When both tiers share one box — the
    dev setup — the ini names this host's own LAN IP, and a rootless podman container
    cannot route to its host's LAN address: the connect hangs until the OS gives up,
    which surfaces as an NER activity stalling for minutes with zero CPU load.

    Podman (and Docker Desktop) inject `host.containers.internal` into every
    container's /etc/hosts pointing at the host gateway, which is routable. Remote
    hosts are returned unchanged — they are reachable from the container as-is.
    """
    if host in local_ip_addresses():
        return "host.containers.internal"
    return host


def port_is_free(port, bind_ips):
    for ip in bind_ips:
        sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        try:
            sock.bind((ip, port))
        except OSError:
            return False
        finally:
            sock.close()
    return True


def project_published_ports(rt, side):
    """Host ports already published by THIS compose project's own containers — a
    redeploy must not fail its own port preflight on the running stack."""
    filters = ["label=com.docker.compose.project=%s" % project_name(side)]
    if side == "main":
        # Serena is its own project (hoover4-devtools) but is deployed by this side.
        filters.append("name=^hoover4-serena$")
    ports = set()
    for flt in filters:
        result = rt.run(["ps", "--filter", flt, "--format", "{{.Ports}}"],
                        capture_output=True, text=True)
        for token in result.stdout.replace("\n", " ").split():
            # tokens look like 0.0.0.0:21900->8123/tcp or 21900->8123/tcp
            match = re.match(r"(?:[\d.]+:)?(\d+)->", token)
            if match:
                ports.add(int(match.group(1)))
    return ports


def expected_ports(cfg, side):
    """[(service, port)] this side publishes with the current ini. Shared by the port
    preflight and the post-`down` wait so the two can never disagree."""
    if side == "ai":
        entries = []
        for flag, rel, svc in AI_OVERLAYS:
            if rel in selected_overlays(cfg, "ai"):
                entries.append((svc, "ai_services", flag.replace("_enabled", "_port")
                                if flag != "llm_selfhosted" else "vllm_port"))
        return [(svc, int(cfg.get(sec, key))) for svc, sec, key in entries]
    checks = [(svc, int(key) if sec is None else int(cfg.get(sec, key)))
              for svc, sec, key in MAIN_PUBLISHED]
    if cfg.get_bool("main_services", "serena_enabled"):
        checks.append(("hoover4-serena", int(cfg.get("main_services", "serena_port"))))
    return checks


def preflight_ports(cfg, side, rt):
    own = project_published_ports(rt, side)
    taken = []
    checks = expected_ports(cfg, side)
    if side == "ai":
        bind_ips = [cfg.get("ai_services", "bind_ip")]
    else:
        # Services bind either loopback or all interfaces; a port is unusable if
        # either fails.
        bind_ips = ["127.0.0.1", "0.0.0.0"]
    for svc, port in checks:
        if port in own:
            continue  # already published by this project's own running container
        if not port_is_free(port, bind_ips):
            taken.append((svc, port))
    if taken:
        detail = "\n".join("    port %d wanted by %s" % (p, s) for s, p in taken)
        fail("ports already in use:\n%s" % detail)


