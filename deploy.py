def _host_resolvers():
    """Upstream resolvers from the host's resolv.conf, skipping 127.* stubs.

    A 127.* nameserver (systemd-resolved's 127.0.0.53) is a host-local stub; a
    container cannot reach it, and aardvark-dns forwarding to it is the flaky
    configuration that wedges external DNS for the whole stack while leaving
    container-name resolution working, so the breakage looks like an app bug.
    """
    resolvers = []
    try:
        with open("/etc/resolv.conf", "r", encoding="utf-8") as fh:
            for line in fh:
                parts = line.split()
                if len(parts) == 2 and parts[0] == "nameserver" \
                        and not parts[1].startswith("127."):
                    resolvers.append(parts[1])
    except OSError:
        pass
    return resolvers


def ensure_network(rt, name):
    """Create the network if missing, with explicit DNS resolvers attached.

    Fresh podman networks have no upstream DNS until resolvers are attached, so
    create with settings from the host's resolv.conf, falling back to public
    resolvers when the host only has a local stub.

    An existing network is also checked: podman cannot change resolvers on a
    live network, so one without them (e.g. created by compose before this
    check existed) is removed and recreated. Possible only when nothing is
    attached, i.e. right after a `--reset`. With containers attached we warn
    and keep the network as-is."""
    resolvers = _host_resolvers()
    if rt.name == "podman" and not resolvers:
        resolvers = ["1.1.1.1", "8.8.8.8"]
    existing = rt.run(["network", "inspect", name],
                      capture_output=True, text=True)
    if existing.returncode == 0:
        if rt.name != "podman":
            return
        try:
            info = json.loads(existing.stdout)[0]
        except (ValueError, IndexError):
            return
        if info.get("network_dns_servers"):
            return
        if info.get("containers"):
            print("WARNING: network %s has no DNS resolvers and containers are "
                  "attached; run ./deploy --reset to recreate it with DNS "
                  "(external lookups from containers will be flaky until then)"
                  % name)
            return
        print("network %s exists without DNS resolvers, so it is recreated (dns: %s)"
              % (name, ", ".join(resolvers)))
        rm = rt.run(["network", "rm", name], capture_output=True, text=True)
        if rm.returncode != 0:
            fail("could not remove DNS-less network %s: %s"
                 % (name, rm.stderr.strip()))
    args = ["network", "create"]
    if rt.name == "podman":
        for resolver in resolvers[:3]:
            args += ["--dns", resolver]
    # docker compose adopts a network it did not create only when that network carries
    # the labels compose would have set itself; without them it refuses the whole `up`
    # with "network ... has incorrect label com.docker.compose.network". podman-compose
    # does not check, which is why creating the network here was invisible until a
    # deploy on plain docker. On both sides the compose network KEY, its `name:` and
    # the project name are the same string, so one value fills all three labels.
    args += ["--label", "com.docker.compose.project=%s" % name,
             "--label", "com.docker.compose.network=%s" % name]
    print("creating network %s (dns: %s)" % (name, ", ".join(resolvers) or "default"))
    result = rt.run(args + [name], capture_output=True, text=True)
    if result.returncode != 0:
        fail("could not create network %s: %s" % (name, result.stderr.strip()))


def verify_network_dns(rt, cfg, side):
    """Verify name resolution between two containers of the stack before declaring
    success. A fresh podman network without resolvers is the failure this catches."""
    result = rt.run(["ps", "--filter", "label=com.docker.compose.project=%s"
                     % project_name(side), "--format", "{{.Names}}"],
                    capture_output=True, text=True)
    names = [n for n in result.stdout.split() if n]
    if len(names) < 2:
        return
    first, second = names[0], names[1]
    check = rt.run(["exec", first, "python", "-c",
                    "import socket; print(socket.gethostbyname('%s'))" % second],
                   capture_output=True, text=True)
    if check.returncode != 0:
        check = rt.run(["exec", first, "getent", "hosts", second],
                       capture_output=True, text=True)
    if check.returncode != 0:
        fail("containers on the %s network cannot resolve each other "
             "(%s -> %s failed). Fresh podman networks need resolvers attached"
             % (project_name(side), first, second))
    print("network %s: %s resolves %s" % (project_name(side), first, second))


