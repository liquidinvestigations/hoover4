def port_is_free(port, bind_ips):
    for ip in bind_ips:
        sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        try:
            sock.bind((ip, port))
        except OSError:
            return False
        finally:
            sock.close()
    return True


def project_published_ports(rt, side):
    """Host ports already published by THIS compose project's own containers, a
    redeploy must not fail its own port preflight on the running stack."""
    filters = ["label=com.docker.compose.project=%s" % project_name(side)]
    if side == "main":
        # Serena is its own project (hoover4-devtools) but is deployed by this side.
        filters.append("name=^hoover4-serena$")
    ports = set()
    for flt in filters:
        result = rt.run(["ps", "--filter", flt, "--format", "{{.Ports}}"],
                        capture_output=True, text=True)
        for token in result.stdout.replace("\n", " ").split():
            # tokens look like 0.0.0.0:21900->8123/tcp or 21900->8123/tcp
            match = re.match(r"(?:[\d.]+:)?(\d+)->", token)
            if match:
                ports.add(int(match.group(1)))
    return ports


def expected_ports(cfg, side):
    """[(service, port)] this side publishes with the current ini. Shared by the port
    preflight and the post-`down` wait so the two can never disagree."""
    if side == "ai":
        entries = []
        for flag, rel, svc in AI_OVERLAYS:
            if rel in selected_overlays(cfg, "ai"):
                entries.append((svc, "ai_services", flag.replace("_enabled", "_port")
                                if flag != "llm_selfhosted" else "vllm_port"))
                if flag == "llm_selfhosted":
                    # The structured server of the same container has its own port.
                    entries.append((svc, "ai_services", "vllm_structured_port"))
        return [(svc, int(cfg.get(sec, key))) for svc, sec, key in entries]
    backdoor_on = cfg.get_bool("main_services", "development_auth_backdoor_enabled")
    checks = []
    for svc, sec, key in MAIN_PUBLISHED:
        port = int(key) if sec is None else int(cfg.get(sec, key))
        if svc is None:
            # The website's published port: hoover4-development-auth-backdoor holds
            # it when the flag is on, hoover4-website holds it otherwise.
            svc = ("hoover4-development-auth-backdoor" if backdoor_on
                   else "hoover4-website")
        if svc in INTERNET_TOOL_SERVICES and not cfg.internet_tools_enabled():
            continue
        if svc in RESEARCH_AGENT_SERVICES and not research_agents_enabled(cfg):
            continue
        checks.append((svc, port))
    if cfg.get_bool("main_services", "serena_enabled"):
        checks.append(("hoover4-serena", int(cfg.get("main_services", "serena_port"))))
    return checks


def preflight_ports(cfg, side, rt):
    own = project_published_ports(rt, side)
    taken = []
    checks = expected_ports(cfg, side)
    if side == "ai":
        bind_ips = [cfg.get("ai_services", "bind_ip")]
    else:
        # Services bind either loopback or all interfaces; a port is unusable if
        # either fails.
        bind_ips = ["127.0.0.1", "0.0.0.0"]
    for svc, port in checks:
        if port in own:
            continue  # already published by this project's own running container
        if not port_is_free(port, bind_ips):
            taken.append((svc, port))
    if taken:
        detail = "\n".join("    port %d wanted by %s" % (p, s) for s, p in taken)
        fail("ports already in use:\n%s" % detail)


