def compose_up(cfg, side, rt, build):
    files = compose_files(cfg, side)
    if build:
        build_cmd = rt.compose_prefix()
        for f in files:
            build_cmd += ["-f", f]
        # `up -d` after a rebuild keeps the old image; build and force-recreate.
        run_or_fail(build_cmd + ["build"])
        up_args = ["up", "-d", "--force-recreate"]
    else:
        up_args = ["up", "-d"]
    if side == "ai" and "compose/vllm.yaml" in selected_overlays(cfg, "ai"):
        ensure_dgemma_image(cfg, rt)
        ensure_dgemma_weights(cfg, rt)
    run_or_fail(compose_command(cfg, side, rt, up_args))
    if side == "main":
        stop_disabled_internet_tools(cfg, rt)
        stop_disabled_research_agents(cfg, rt)
    if rt.name == "podman" and build:
        podman_stale_image_fix(cfg, side, rt, files)
    if side == "main":
        apply_temporal_retention(cfg, rt)
        report_worker_stop_timeout(cfg, rt)


