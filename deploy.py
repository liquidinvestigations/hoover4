def compose_up(cfg, side, rt, build):
    files = compose_files(cfg, side)
    if build:
        build_cmd = rt.compose_prefix()
        for f in files:
            build_cmd += ["-f", f]
        # `up -d` after a rebuild keeps the old image; build and force-recreate.
        run_or_fail(build_cmd + ["build"])
        up_args = ["up", "-d", "--force-recreate"]
    else:
        up_args = ["up", "-d"]
    run_or_fail(compose_command(cfg, side, rt, up_args))
    if rt.name == "podman" and build:
        podman_stale_image_fix(cfg, side, rt, files)
    if side == "main":
        report_worker_stop_timeout(cfg, rt)


def report_worker_stop_timeout(cfg, rt):
    """Say out loud whether the worker's graceful shutdown period is actually reachable.

    `stop_grace_period` in the compose file is not the whole story under podman, and the
    difference is invisible unless something says so -- which is the entire reason this
    prints rather than staying silent on the happy path.

    podman-compose applies the grace period only when IT stops the container: it passes
    `-t <seconds>` to `podman stop` on down/stop/restart. It does NOT write the value into
    the container, and `podman update` cannot set it afterwards -- `--stop-timeout` is
    accepted only at creation. So the container keeps podman's own default of 10 seconds,
    and anything that stops it directly (`docker stop`, `docker restart`, a supervisor,
    a person) kills through the graceful period at ten seconds no matter what the
    configuration says.

    A worker SIGKILLed part-way through draining is the exact failure the graceful period
    exists to prevent, so the number that is really in force is printed either way.
    """
    want = worker_graceful_shutdown_seconds(cfg) + WORKER_SHUTDOWN_MARGIN_SECONDS
    got = rt.run(["inspect", "hoover4-worker", "--format", "{{.Config.StopTimeout}}"],
                 capture_output=True, text=True)
    if got.returncode != 0:
        return
    raw = got.stdout.strip()
    try:
        effective = int(raw)
    except ValueError:
        return
    if effective >= want:
        print("preflight: worker stop grace period %ds, as configured" % effective)
        return
    print("preflight: WARNING: hoover4-worker was created with a %ds stop timeout, not "
          "the configured %ds — %s drops stop_grace_period at creation and cannot set it "
          "afterwards." % (effective, want, rt.describe()))
    print("preflight:          `./deploy --down` and `%s compose stop` still honour the "
          "full period; a direct `stop`/`restart` of this container does not, and must "
          "pass `-t %d` itself." % (rt.describe(), want))


def podman_stale_image_fix(cfg, side, rt, files):
    """podman-compose sometimes leaves the old container running the old image id even
    after --force-recreate. Detect that and fall back to `rm -f --depend` + up."""
    ps = rt.run(["ps", "--filter", "label=com.docker.compose.project=%s"
                 % project_name(side), "--format",
                 "{{.Names}} {{.Image}} {{.ImageID}}"], capture_output=True, text=True)
    stale = []
    for line in ps.stdout.splitlines():
        parts = line.split()
        if len(parts) < 3:
            continue
        name, image, running_id = parts[0], parts[1], parts[2]
        inspect = rt.run(["image", "inspect", image, "--format", "{{.Id}}"],
                         capture_output=True, text=True)
        latest = inspect.stdout.strip()
        if latest and running_id and latest != running_id:
            stale.append(name)
    if not stale:
        return
    print("podman kept old images running for: %s — recreating" % ", ".join(stale))
    rt.run(["rm", "-f", "--depend"] + stale)
    run_or_fail(compose_command(cfg, side, rt, ["up", "-d"]))


def reprobe_embeddings(rt):
    """Re-record what the GPU tier serves, after `--ai-services` brought it up.

    `server_settings.embeddings_serving_model` is the *truth* the whole vector half is
    built on, and bringing the AI tier up with a different `embeddings_model` is precisely
    when it goes stale. Every consumer then correctly refuses — which is the hard part to
    diagnose, because nothing is broken and nothing says so.

    Best effort, and never fatal to the deploy: the worker lives on the main stack, which
    may be on another host or simply not running. A model still loading is the normal
    case here, and the workers probe again at their own startup.
    """
    ps = rt.run(["ps", "--filter", "name=hoover4-worker", "--format", "{{.Names}}"],
                capture_output=True, text=True)
    if "hoover4-worker" not in (ps.stdout or ""):
        print("skipping the embeddings re-probe: hoover4-worker is not running here "
              "(run `./deploy` then `docker exec hoover4-worker uv run python main.py "
              "probe-embeddings` if the model changed)")
        return
    print("re-probing the embeddings endpoint...")
    result = rt.run(["exec", "hoover4-worker", "uv", "run", "python", "main.py",
                     "probe-embeddings"], capture_output=True, text=True)
    output = (result.stdout or "").strip() or (result.stderr or "").strip()
    if result.returncode != 0:
        print("WARNING: embeddings probe failed (%s); server_settings is unchanged and "
              "the embed/index stages will refuse until it succeeds" % output)
        return
    for line in output.splitlines():
        print("  %s" % line)


def serena_command(cfg, rt, extra_args):
    # --env-file is NOT optional here. Compose auto-discovers `.env` from the directory
    # of the first -f file; the main stack's first file is the base compose in
    # MAIN_COMPOSE_DIR, so it finds the generated .env, but the serena overlay lives in
    # MAIN_COMPOSE_DIR/compose/, which has none. Without this the overlay renders with
    # an empty ${HOOVER4_REPO_ROOT} and the repo bind mount fails with the singularly
    # unhelpful "Error: container directory cannot be empty".
    #
    # Do NOT add --project-directory: relative paths (the `../serena` build context)
    # resolve against the declaring file's own directory, which is already correct.
    cmd = rt.compose_prefix() + ["--env-file", str(MAIN_COMPOSE_DIR / ".env"),
                                 "-p", SERENA_PROJECT,
                                 "-f", str(MAIN_COMPOSE_DIR / SERENA_OVERLAY)]
    return cmd + extra_args


def compose_up_serena(cfg, rt, build):
    if not cfg.get_bool("main_services", "serena_enabled"):
        return
    if build:
        run_or_fail(serena_command(cfg, rt, ["build"]))
        run_or_fail(serena_command(cfg, rt, ["up", "-d", "--force-recreate"]))
    else:
        run_or_fail(serena_command(cfg, rt, ["up", "-d"]))


def wait_for_ports_released(cfg, side, rt, timeout_seconds=60):
    """Block until this project's published ports are actually free again.

    `compose down` returns as soon as the containers are gone, but on podman the
    project's pod publishes the ports on its infra container, and that teardown is
    asynchronous. So `./deploy --reset && ./deploy` would fail its own port preflight
    with a port it had just released ("port 12345 wanted by hoover4-website") — a race
    that looks exactly like a genuine conflict and sends you hunting for a process that
    does not exist. Wait it out here instead of making every caller rediscover it.
    """
    # Serena is a separate compose project that deliberately survives down/reset, so
    # its port is still held on purpose — waiting on it would burn the whole timeout
    # and print a warning about working as intended.
    wanted = [(svc, port) for svc, port in expected_ports(cfg, side)
              if svc != "hoover4-serena"]
    if not wanted:
        return
    bind_ips = ["0.0.0.0"]
    deadline = time.time() + timeout_seconds
    while True:
        busy = sorted(p for _, p in wanted if not port_is_free(p, bind_ips))
        if not busy:
            return
        if time.time() >= deadline:
            print("warning: ports still held %ds after down: %s"
                  % (timeout_seconds, ", ".join(str(p) for p in busy)), file=sys.stderr)
            return
        time.sleep(1)


def compose_down(cfg, side, rt):
    run_or_fail(compose_command(cfg, side, rt, ["down"]))
    wait_for_ports_released(cfg, side, rt)


def compose_reset(cfg, side, rt, reset_caches):
    """Scoped reset: only this compose project's containers and volumes. Model-cache
    volumes are preserved by name unless --reset-caches; the Serena container and its
    volume are never touched — killing it mid-session drops the MCP connection the
    agent is using to do the work. Serena survives by construction: it is a separate
    compose project (hoover4-devtools), so this project's `down` never selects it."""
    proj = project_name(side)
    run_or_fail(compose_command(cfg, side, rt, ["down"]))
    wait_for_ports_released(cfg, side, rt)
    volumes = rt.run(["volume", "ls", "--format", "{{.Name}}"],
                     capture_output=True, text=True).stdout.split()
    doomed = []
    for vol in volumes:
        if not vol.startswith(proj + "_"):
            continue
        if any(vol.endswith(sfx) for sfx in PROTECTED_VOLUME_SUFFIXES):
            continue
        if not reset_caches and any(vol.endswith(sfx) for sfx in CACHE_VOLUME_SUFFIXES):
            print("reset: preserving cache volume %s" % vol)
            continue
        doomed.append(vol)
    if doomed:
        run = rt.run(["volume", "rm", "-f"] + doomed, capture_output=True, text=True)
        if run.returncode != 0:
            fail("could not remove volumes: %s" % run.stderr.strip())
        for vol in doomed:
            print("reset: removed volume %s" % vol)


# Temporal's own persistence: the workflow history store and its visibility index.
# Scoped separately from --reset because the shard count can only change by dropping
# them, and there is no reason to lose the corpus to do it.
TEMPORAL_SERVICES = ["temporal-ui", "temporal", "temporal-cassandra",
                     "temporal-elasticsearch"]
TEMPORAL_VOLUME_SUFFIXES = ("temporal_cassandra", "temporal_elasticsearch")


def compose_reset_temporal(cfg, side, rt):
    """Drop Temporal's history and visibility stores, keeping every other volume.

    What is lost is workflow history, which retention already caps at 24 h with
    archival off. What is kept is everything the corpus lives in -- ClickHouse, Garage,
    Manticore, Redis. Running ingests do not survive: their workflows are gone, and
    P0 re-scans a dataset from disk on the next run.
    """
    if side != "main":
        fail("--reset-temporal applies to the main stack; drop --ai-services")
    proj = project_name(side)
    run_or_fail(compose_command(cfg, side, rt, ["stop"] + TEMPORAL_SERVICES))
    # Removal goes through the runtime, not compose: podman-compose has no `rm`
    # subcommand at all. These four carry a fixed `container_name`, so the compose
    # service name and the container name are the same string.
    #
    # `--depend` is podman-only -- docker rejects the flag, and because the volume
    # removal below cannot proceed while a container still holds it, a silently failed
    # `rm` turns into "volume is in use" several steps later. Fail loudly here instead.
    args = ["rm", "-f"] + (["--depend"] if rt.name == "podman" else []) + TEMPORAL_SERVICES
    run = rt.run(args, capture_output=True, text=True)
    if run.returncode != 0:
        still = rt.run(["ps", "-a", "--format", "{{.Names}}"],
                       capture_output=True, text=True).stdout.split()
        left = [c for c in TEMPORAL_SERVICES if c in still]
        if left:
            fail("could not remove %s: %s" % (", ".join(left), run.stderr.strip()))
    volumes = rt.run(["volume", "ls", "--format", "{{.Name}}"],
                     capture_output=True, text=True).stdout.split()
    doomed = [v for v in volumes if v.startswith(proj + "_")
              and any(v.endswith(sfx) for sfx in TEMPORAL_VOLUME_SUFFIXES)]
    if not doomed:
        print("reset-temporal: no temporal volumes to remove")
    else:
        run = rt.run(["volume", "rm", "-f"] + doomed, capture_output=True, text=True)
        if run.returncode != 0:
            fail("could not remove volumes: %s" % run.stderr.strip())
        for vol in doomed:
            print("reset-temporal: removed volume %s" % vol)
    print("reset-temporal: run ./deploy to re-initialise at %s history shards"
          % cfg.get("main_services", "temporal_history_shards"))


def run_or_fail(cmd):
    print("+ %s" % " ".join(cmd))
    result = subprocess.run(cmd)
    if result.returncode != 0:
        fail("command failed with exit code %d" % result.returncode)


